class Logic
{
    void  PrintReverse(int n)
    {    
        int iCnt=0;

        for(iCnt=n;iCnt>=1;iCnt--)
        {
            System.out.println(iCnt);
        }
    }
}
class Assignment_20_2
{
    public static void main(String Arr[])
    {
        Logic obj=new Logic();
        obj.PrintReverse(10);
    }
 
}

 

 
 
