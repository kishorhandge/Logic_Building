float Percentage(int iTotal, int iObt)
{
    float fRes = 0.0;

    if (iTotal == 0)
    {   
        printf(" Total marks canot be zero.\n");
    }
    if(iObt==0)
    {
        printf("Obtained marks canot be zero\n");
    }

    fRes = ((float)iObt / iTotal)*100.0;

    return fRes;
}
int main()
{    
    int iValue1 = 0, iValue2 = 0;
    float fRet = 0.0;

    printf("Please Enter total marks\n");
    scanf("%d", &iValue1);

    printf("Please Enter obtained marks\n");
    scanf("%d", &iValue2);

    fRet = Percentage(iValue1, iValue2);

    printf("Percentage is:%f", fRet);

    return 0;
}
