#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  PrintFactors
//  Description:    It is use to display all factors
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           28/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
void PrintFactors(int number)
{

    int iCnt = 0;

    for (iCnt = 1; iCnt < number; iCnt++)
    {
        if (number % iCnt == 0)
        {
            printf("%d\t", iCnt);
        }
    }
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int number = 0;

    printf("Enter number\n");
    scanf("%d", &number);

    PrintFactors(number);

    return 0;
}
