void CheckEvenOdd(int num)
{

    if (num % 2 == 0)
    {
        printf("Number is Even\n");
    }
    else
    {
        printf("Number is Odd\n");
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int number = 0;

    printf("Enter the Number\n");
    scanf("%d", &number);

    CheckEvenOdd(number);

    return 0;
}

