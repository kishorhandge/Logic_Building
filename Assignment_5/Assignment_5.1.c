/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  CheckEvenOdd
//  Description:    It is use check the given number is even or odd
//  Input:          int
//  Output:         even,odd
//  Author:         Kishor Suryabhan Handge
