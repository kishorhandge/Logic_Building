#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  FindMax
//  Description:    It is use find the maximum of two numbers
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           23/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////

int FindMax(int a, int b)
{
    if (a > b)
    {
        return a;
    }
    else
    {
        return b;
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int num1 = 0;
    int num2 = 0;
    int result = 0;

    printf("Enter two Numbers\n");
    scanf("%d %d", &num1, &num2);

    result = FindMax(num1, num2);

    printf("The Maximum is: %d\n", result);

    return 0;
}
