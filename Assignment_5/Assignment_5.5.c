int  FindLargest(int x,int y, int z)
{
    if(x>y && x>z)
    {
        return x;
    }
    else if(y>x && y>z)
    {
        return y;
    }
    else if(z>x && z>y)
    {
        return z;
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int a,b,c,result;

    printf("Enter  three numbers: \n");
    scanf("%d %d %d",&a,&b,&c);

    result=FindLargest(a,b,c);
    printf("Largest number is :%d\n",result);

    return 0;
}
