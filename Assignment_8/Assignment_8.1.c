#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Number
//  Description:    It is use to display State of number
//  Input:          int
//  Output:         void
//  Author:         Kishor Suryabhan Handge
//  Date:           27/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
void Number(int iNo)
{

    if (iNo < 50)
    {
        printf("Small\n");
    }
    else if (iNo > 50 && iNo < 100)
    {
        printf("Medium");
    }
    else if (iNo > 100)
    {
        printf("Large");
    }
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number\n");
    scanf("%d", &iValue);

    Number(iValue);

    return 0;
}
