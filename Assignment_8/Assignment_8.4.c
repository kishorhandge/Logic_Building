void Table(int iNo)
{

    int iCnt = 0;

    for (iCnt = 1; iCnt <= 10; iCnt++)
    {
        printf("%d\t",iCnt*iNo);
    }
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number\n");
    scanf("%d", &iValue);

    Table(iValue);

    return 0;
}
