#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Pattern
//  Description:    It is use to display $ and * on console
//  Input:          string
//  Output:         $ *
//  Author:         Kishor Suryabhan Handge
//  Date:           25/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
void Pattern(int iNo)
{
    int iCnt = 0;

    for (iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("$\t *\t");
    }
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number\n");
    scanf("%d", &iValue);

    Pattern(iValue);

    return 0;
}
