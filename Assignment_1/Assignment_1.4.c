/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Check  
//  Description:    It is use to Check Number Divisible by particuler number or not
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
