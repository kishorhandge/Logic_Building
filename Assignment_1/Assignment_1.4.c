bool Check(int iNo)
{
    if ((iNo % 5) == 0)             //Buisness Logic
    {
        return true;
    }
    else
    {
        return false;
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0;

    int iRet = false;

    printf("Enter the Number\n");
    scanf("%d", &iValue);

    iRet = Check(iValue);
    if (iRet == true)
    {
        printf("Divisible by 5");
    }
    else
    {
        printf("Not Divisible by 5");
    }

    return 0;
}

