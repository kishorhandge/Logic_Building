#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Accept  
//  Description:    It is use to Print the * on Console
//  Input:          int
//  Output:         *
//  Author:         Kishor Suryabhan Handge
//  Date:           18/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////

void Accept()
{
    int iCnt = 0;

    for (iCnt = 1; iCnt <= 5; iCnt++)
    {
        printf("*\t");
    }
}


/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0;
    iValue=5;

    Accept(iValue);

    return 0;
}
