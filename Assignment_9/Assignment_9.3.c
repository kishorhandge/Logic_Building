int EvenFactorial(int iNo)
{

    int iCnt = 0;
    int iFact = 1;
    
    //Updater
    if(iNo<0)
    {
        iNo=-iNo;
    }

    for (iCnt = iNo; iCnt >= 1; iCnt--)
    {
        if (iCnt % 2 == 0)
        {
            iFact = iFact * iCnt;
        }
    }

    return iFact;
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter number\n");
    scanf("%d", &iValue);

    iRet = EvenFactorial(iValue);

    printf("Factorial of number is:  %d", iRet);

    return 0;
}
