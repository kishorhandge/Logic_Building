#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    It is use to display pattern
//  Input:          int
//  Output:         void
//  Author:         Kishor Suryabhan Handge
//  Date:           27/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
void Display(int iNo)
{

    int iCnt=0;

    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
        printf("*\t");

    }
    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
        printf("#\t");

    }
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter number\n");
    scanf("%d", &iValue);

    Display(iValue);

    return 0;
}
