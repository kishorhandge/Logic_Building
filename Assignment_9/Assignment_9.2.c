int DollerToINR(int iNo)
{

    int iINR = 70;
    int iRes = 1;

    iRes = iINR * iNo;

    return iRes;
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet = 0;

    printf("Enter number of USD\n");
    scanf("%d", &iValue);

    iRet = DollerToINR(iValue);

    printf("Value in INR is : %d", iRet);

    return 0;
}
