#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  DollerToINR
//  Description:    It is use to convert doller into indian Rs
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           27/10/2025
