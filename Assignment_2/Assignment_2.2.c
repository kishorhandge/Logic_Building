#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Display 
//  Description:    It is use to take number from user and print the *
//  Input:          int
//  Output:         *
//  Author:         Kishor Suryabhan Handge
//  Date:           18/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////

int Display(int iNo)
{
    

    //Updater
    if (iNo < 0)
    {
        iNo=-iNo;
    }

    while(iNo>0)
    {
        printf("*\t");      //Buisness Logic
        iNo--;
    }                    

     
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the Number\n");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}
