#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Display
//  Description:    We have to accept two number and display first number in second number of times
//  Input:          int,int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           18/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo, int iFrequency)
{
    int iCnt = 0;

    // Updater
     if (iNo < 0)
     {
         iNo=-iNo;
     }
    for (iCnt = 0; iCnt < iFrequency; iCnt++)
    {
        printf("%d\t", iNo);
    }
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iCount = 0;

    printf("Enter the Number\n");
    scanf("%d", &iValue);

    printf("Enter the Frequency\n");
    scanf("%d", &iCount);

    Display(iValue, iCount);

    return 0;
}

