#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Display 
//  Description:    If the number less than 10 (iNo<10) print "Hello" ,otherwise print "Demo"
//  Input:          int
//  Output:         "Hello","Demo"
//  Author:         Kishor Suryabhan Handge
//  Date:           18/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////

void Display(int iNo)
{
    
    if (iNo<10)
    {
        printf("Hello");
    }
    else
    {
        printf("Demo");
    }
      
    }                    

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;

    printf("Enter the Number\n");
    scanf("%d",&iValue);

    Display(iValue);

    return 0;
}
