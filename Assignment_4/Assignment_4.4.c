int SumNonFact(int iNo)
{
    int iCnt = 0;
    int iSum=0;

    for (iCnt = 1; iCnt <= iNo; iCnt++)
    {
        if (iNo % iCnt != 0)
        {
            iSum=iSum+iCnt;
        }
    }
    return iSum;
}

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    int iRet=0;

    printf("Enter the Number\n");
    scanf("%d", &iValue);

    iRet=SumNonFact(iValue);

    printf("%d",iRet);

    return 0;
}

