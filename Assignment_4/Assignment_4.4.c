#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  SumNonFact
//  Description:    It is use find the Summation Non factors
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           20/10/2025
