#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  Print_Numbers
//  Description:    It is use to display number
//  Input:          int
//  Output:         void
//  Author:         Kishor Suryabhan Handge
//  Date:           28/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
void Print_Numbers(int limit)
{

    int iCnt = 0;

    for (iCnt = 1; iCnt <= limit; iCnt++)
    {
        printf("%d\t", iCnt);
    }
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int limit;

    printf("Enter number\n");
    scanf("%d", &limit);

    Print_Numbers(limit);

    return 0;
}
