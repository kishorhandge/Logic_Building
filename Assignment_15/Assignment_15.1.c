/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  CountEven
//  Description:    It is use to display even count of a number
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           29/10/2025
