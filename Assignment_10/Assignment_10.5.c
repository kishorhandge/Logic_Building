#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  SquareMeter
//  Description:    It is use to convert square feet to square meter
//  Input:          int
//  Output:         double
//  Author:         Kishor Suryabhan Handge
//  Date:           27/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
double SquareMeter(int iValue)
{
    float fRes = 1.0;

    fRes = 0.0929 *iValue;

    return fRes;
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    double dRet = 0.0;

    printf("Enter area in square feet \n");
    scanf("%d", &iValue);

    dRet = SquareMeter(iValue);

    printf("%d square feet into square meter is:  %lf", iValue, dRet);

    return 0;
}
