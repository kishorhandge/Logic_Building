#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  KMtoMeter
//  Description:    It is use to convert km to meter
//  Input:          int
//  Output:         int
//  Author:         Kishor Suryabhan Handge
//  Date:           27/10/2025
/////////////////////////////////////////////////////////////////////////////////////////////////
int KMtoMeter(int iNo)
{
    
    int iMeter=1;

    iMeter=1000*iNo;

    return iMeter;
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    int iValue=0;
    int iRet = 0;

    printf("Enter distance\n");
    scanf("%d", &iValue);

    iRet=KMtoMeter(iValue);

    printf(" %d KM to Meter is : %d meter",iValue, iRet);

    return 0;
}
