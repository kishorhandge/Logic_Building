double CircleArea(float fRadius)
{
    
    double dArea=1.0;

    dArea=3.14*fRadius*fRadius;

    return dArea;
}
/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Entry point Function for the application
//
/////////////////////////////////////////////////////////////////////////////////////////////////

int main()
{
    float fValue = 0.0;
    double dRet = 0.0;

    printf("Enter radius\n");
    scanf("%f", &fValue);

    dRet=CircleArea(fValue);

    printf("The Radius of Circle is %f", dRet);

    return 0;
}
