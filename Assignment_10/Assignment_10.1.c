#include <stdio.h>

/////////////////////////////////////////////////////////////////////////////////////////////////
//
//  Function Name:  CircleArea
//  Description:    It is use to find area of a circle
//  Input:          float
//  Output:         float
//  Author:         Kishor Suryabhan Handge
//  Date:           27/10/2025
